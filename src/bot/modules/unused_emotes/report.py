def parse_cutoff(value: str) -> datetime:
    """Return the UTC cutoff for a ``<number><y|w|d|m>`` timeframe.

    Invalid input raises ``ValueError`` so the command can reply with usage
    instead of silently reporting on a different window than requested.
    """
    match = CUTOFF_PATTERN.fullmatch(value.strip())
    if match is None:
        raise ValueError("invalid cutoff")
    days = int(match.group(1)) * UNIT_DAYS[match.group(2).lower()]
    if days < 1:
        raise ValueError("cutoff must be at least one day")
    return datetime.now(UTC) - timedelta(days=days)


def parse_threshold(value: str, *, default: int, max_threshold: int) -> int:
    """Return a validated usage threshold; invalid input raises ``ValueError``."""
    text = value.strip()
    if not text:
        return default
    if re.fullmatch(r"\d+", text) is None:
        raise ValueError("invalid threshold")
    number = int(text)
    if not 1 <= number <= max_threshold:
        raise ValueError("threshold out of range")
    return number


def build_patterns(emote: str) -> tuple[str, str]:
    """Build whole-word and ``!ecount`` exclusion regexes for PostgreSQL.

    Emote names from 7TV are escaped, so characters outside Twitch's usual
    alphabet are safe and do not need to be skipped.
    """
    escaped = re.escape(emote)
    return (
        rf"(?<!{WORD_BOUNDARY}){escaped}(?!{WORD_BOUNDARY})",
        rf"!ecount\s+{escaped}",
    )


def _escape(value: object) -> str:
    return html.escape(str(value), quote=True)


def _emote_image_url(emote_data: dict) -> str:
    """Return a validated https image URL for an emote, or an empty string."""
    host = emote_data.get("host")
    if not isinstance(host, dict):
        data = emote_data.get("data", {})
        host = data.get("host", {}) if isinstance(data, dict) else {}
    if not isinstance(host, dict):
        return ""

    url_base = str(host.get("url", "") or "")
    if url_base.startswith("//"):
        url_base = "https:" + url_base
    if not url_base.startswith("https://"):
        return ""

    files = host.get("files") or []
    name = ""
    for entry in files:
        if isinstance(entry, dict) and entry.get("name") == "2x.webp":
            name = "2x.webp"
            break
    if not name and files and isinstance(files[0], dict):
        name = str(files[0].get("name", "") or "")
    if not name and emote_data.get("id"):
        name = "2x.webp"
    if not name:
        return ""
    return f"{url_base.rstrip('/')}/{quote(name, safe='._-')}"


def render_report(
    under_threshold: list[tuple[dict, str, int]],
    total_emotes: int,
    cutoff: datetime,
    threshold: int,
    channel: str,
) -> str:
    """Build the full HTML report; every dynamic value is HTML-escaped."""
    generated = datetime.now(UTC).strftime("%Y-%m-%d %H:%M:%S UTC")
    cutoff_text = cutoff.strftime("%Y-%m-%d %H:%M:%S UTC")
    parts = [
        "<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n"
        '<meta charset="UTF-8">\n'
        '<meta name="viewport" content="width=device-width, initial-scale=1.0">\n'
        "<title>7TV Unused Emotes Report</title>\n"
        f"<style>{STYLE}</style>\n</head>\n<body>\n\n"
        "<h1>7TV Unused Emotes Report</h1>\n"
        f'<p class="subtitle">{_escape(channel)} &mdash; '
        "Emotes Used Below Threshold</p>\n\n"
        '<div class="summary">\n'
        f'  <div class="summary-card"><h3>{total_emotes}</h3><p>Total Active Emotes</p></div>\n'
        f'  <div class="summary-card"><h3>{len(under_threshold)}</h3><p>Under Threshold</p></div>\n'
        f'  <div class="summary-card"><h3>{threshold}</h3><p>Threshold</p></div>\n'
        f'  <div class="summary-card"><h3>{_escape(cutoff_text)}</h3><p>Cutoff</p></div>\n'
        "</div>\n\n"
        f'<p class="meta">Generated: {_escape(generated)}</p>\n\n'
    ]

    if under_threshold:
        parts.append(
            '<div class="section-title">Emotes <span>Under Threshold</span></div>\n'
            "<table>\n<tr><th>#</th><th>Emote</th><th>Usage Count</th></tr>\n"
        )
        for index, (emote_data, name, count) in enumerate(under_threshold, 1):
            safe_name = _escape(name)
            image_url = _emote_image_url(emote_data)
            image = (
                f'<img class="emote-img" src="{_escape(image_url)}" '
                f'alt="{safe_name}" loading="lazy">'
                if image_url
                else ""
            )
            link = f"https://7tv.app/emotes/{quote(str(emote_data.get('id', '')), safe='')}"
            parts.append(
                f"<tr><td>{index}</td>"
                f'<td><div class="emote-cell">{image}'
                f'<a class="emote-name" href="{_escape(link)}" target="_blank">'
                f"{safe_name}</a></div></td>"
                f'<td><span class="count-badge">{count}</span></td></tr>\n'
            )
        parts.append("</table>\n")
    else:
        parts.append(
            '<p class="no-emotes">&#10004; All emotes meet the threshold!</p>\n'
        )

    parts.append(FOOTER)
    parts.append("\n</body>\n</html>\n")
    return "".join(parts)
